-- Run explicitly with npm run db:init. The CLI wraps this file in one transaction.
-- This private schema is accessed by the Next.js server, not the browser Data API.
CREATE SCHEMA IF NOT EXISTS studentpath;
REVOKE ALL ON SCHEMA studentpath FROM PUBLIC, anon, authenticated, service_role;

CREATE TABLE IF NOT EXISTS studentpath.admin_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  salt text NOT NULL,
  password_hash text NOT NULL,
  created_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS studentpath.admin_sessions (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES studentpath.admin_users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS admin_sessions_user ON studentpath.admin_sessions(user_id);
CREATE TABLE IF NOT EXISTS studentpath.login_attempts (
  bucket text PRIMARY KEY,
  started_at bigint NOT NULL,
  count integer NOT NULL
);

CREATE TABLE IF NOT EXISTS studentpath.community_posts (
  id text PRIMARY KEY,
  payload text NOT NULL,
  is_demo integer NOT NULL CHECK (is_demo IN (0, 1)),
  created_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS studentpath.community_featured (
  post_id text PRIMARY KEY REFERENCES studentpath.community_posts(id) ON DELETE CASCADE,
  selected_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS studentpath.editorial_content (
  id text PRIMARY KEY,
  payload text NOT NULL,
  updated_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS studentpath.app_meta (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS studentpath.member_users (
  id text PRIMARY KEY,
  username text NOT NULL UNIQUE,
  display_name text NOT NULL,
  salt text NOT NULL,
  password_hash text NOT NULL,
  created_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS studentpath.member_profiles (
  user_id text PRIMARY KEY REFERENCES studentpath.member_users(id) ON DELETE CASCADE,
  profile_json text NOT NULL,
  updated_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS studentpath.member_sessions (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES studentpath.member_users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS member_sessions_user ON studentpath.member_sessions(user_id);
CREATE TABLE IF NOT EXISTS studentpath.member_auth_attempts (
  bucket text PRIMARY KEY,
  started_at bigint NOT NULL,
  count integer NOT NULL
);
CREATE TABLE IF NOT EXISTS studentpath.member_friendships (
  user_low text NOT NULL REFERENCES studentpath.member_users(id),
  user_high text NOT NULL REFERENCES studentpath.member_users(id),
  requester_id text NOT NULL REFERENCES studentpath.member_users(id),
  status text NOT NULL CHECK (status IN ('pending', 'accepted')),
  created_at bigint NOT NULL,
  PRIMARY KEY (user_low, user_high),
  CHECK (user_low < user_high),
  CHECK (requester_id IN (user_low, user_high))
);
CREATE TABLE IF NOT EXISTS studentpath.member_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id text NOT NULL REFERENCES studentpath.member_users(id),
  recipient_id text NOT NULL REFERENCES studentpath.member_users(id),
  body text NOT NULL,
  client_id text NOT NULL,
  created_at bigint NOT NULL,
  UNIQUE (sender_id, client_id),
  CHECK (sender_id <> recipient_id)
);
CREATE INDEX IF NOT EXISTS member_messages_pair ON studentpath.member_messages(sender_id, recipient_id, id);

-- No browser policies: Next.js verifies the existing HttpOnly session and role.
-- The database owner used by DATABASE_URL can access these tables; API roles cannot.
ALTER TABLE studentpath.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.admin_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.login_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.community_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.community_featured ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.editorial_content ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.app_meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.member_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.member_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.member_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.member_auth_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.member_friendships ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.member_messages ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA studentpath FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA studentpath FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA studentpath
  REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA studentpath
  REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated, service_role;

-- Published site images are public. Uploads go through the authenticated server.
