CREATE TABLE IF NOT EXISTS studentpath.community_comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id text NOT NULL REFERENCES studentpath.community_posts(id) ON DELETE CASCADE,
  author_id text NOT NULL REFERENCES studentpath.member_users(id),
  display_name text NOT NULL,
  body text NOT NULL,
  client_id text NOT NULL,
  UNIQUE (post_id, author_id, client_id)
);
CREATE INDEX IF NOT EXISTS community_comments_thread ON studentpath.community_comments(post_id,id);
ALTER TABLE studentpath.community_comments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON studentpath.community_comments FROM PUBLIC, anon, authenticated, service_role;
CREATE TABLE IF NOT EXISTS studentpath.community_likes (
  post_id text REFERENCES studentpath.community_posts(id) ON DELETE CASCADE,
  author_id text REFERENCES studentpath.member_users(id), PRIMARY KEY(post_id,author_id)
);
CREATE TABLE IF NOT EXISTS studentpath.community_authors (
  post_id text PRIMARY KEY REFERENCES studentpath.community_posts(id) ON DELETE CASCADE,
  author_id text NOT NULL REFERENCES studentpath.member_users(id)
);
ALTER TABLE studentpath.community_likes ENABLE ROW LEVEL SECURITY;
ALTER TABLE studentpath.community_authors ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON studentpath.community_likes, studentpath.community_authors FROM PUBLIC, anon, authenticated, service_role;
