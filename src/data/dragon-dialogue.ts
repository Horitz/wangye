export function landmarkLine(scene: DragonLandmark, visit: number): DragonLine {
  const [zh, ru] = visits[scene][visit % visits[scene].length];
  return { mood: scene === "coin" ? "happy" : "surprised", zh, ru, scene };
}

export function dragonConversation(previous?: DragonMood): DragonLine[] {
  const stories = [...exchanges];
  for (let i = stories.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [stories[i], stories[j]] = [stories[j], stories[i]];
  }
  if (stories[0][0][0] === previous) {
    const other = stories.findIndex(story => story[0][0] !== previous);
    [stories[0], stories[other]] = [stories[other], stories[0]];
  }
  return stories.flatMap(story => story.map(([mood, zh, ru]) => ({ mood, zh, ru })));
}
