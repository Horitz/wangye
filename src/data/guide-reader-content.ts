export function getGuideReaderContent(guide: GuidePreview): GuideReaderContent {
  const details = detailsByGuide[guide.id] ?? fallbackDetails;
  return {
    author: {
      name: text("StudentPath", "StudentPath"),
      role: text("编辑整理 · 非官方指南", "Редакционный обзор · Неофициальная инструкция"),
    },
    slides: [
      { id: `${guide.id}-journey`, title: guide.title, caption: text("先了解流程，再按自己的情况准备。", "Сначала разберитесь в порядке действий, затем готовьтесь для своей ситуации."), kind: "journey" },
      { id: `${guide.id}-documents`, title: text("让准备更清楚", "Разложить подготовку по полочкам"), caption: text("展开进度条目，查看材料与准备说明。", "Раскройте шаги, чтобы увидеть материалы и пояснения."), kind: "documents" },
      { id: `${guide.id}-result`, title: text("每一步，都由你记录", "Каждый шаг отмечаете вы"), caption: text("完成一项再勾选，按自己的节奏继续。", "Отмечайте выполненное и продолжайте в своём темпе."), kind: "result" },
    ],
    steps: details.map(step => ({
      id: `${guide.id}-${step.key}`,
      legacyIndex: step.legacyIndex,
      title: step.title,
      description: guide.steps[step.legacyIndex] ?? text("请向负责部门确认下一步安排。", "Уточните дальнейшие действия в ответственном подразделении."),
      materials: step.materials,
      annotation: step.annotation,
      diagram: step.diagram,
      ...(step.sources ? { sources: step.sources } : {}),
    })),
  };
}
